#include <stdio.h>
#include <string.h>

#define MAX 100

struct lista {
    int qtd;
    float dados[MAX];
    float preco;
};

typedef struct lista Lista;

//-------------------------------------------------------------------------------------------------------------------------------------------------------
//Q1

//-------------------------------------------------------------------------------------------------------------------------------------------------------

int lista_tem_espaco(Lista* li, int n){
    if(li == NULL || n < 0){
        return 0;
    }
    if (li-> qtd + n <= MAX){
        return 1;
    } else{
        return 0;
    }
}


//-------------------------------------------------------------------------------------------------------------------------------------------------------
//Q2
//Implemente a função soma_precos, que devolve a soma do campo preco de todos os produtos armazenados na lista. Se li for NULL, a função deve devolver 0.
//-------------------------------------------------------------------------------------------------------------------------------------------------------

float soma_precos(Lista* li){
    if(li == NULL){
        return 0;
    }
    li->preco = 0;
    for(int i = 0; i < li->qtd; i++){
        li->preco = li->preco + li->dados[i];
    }
    return li->preco;
}



